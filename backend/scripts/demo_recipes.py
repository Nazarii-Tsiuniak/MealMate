@dataclass(frozen=True)
class DemoRecipe:
    key: str
    name: str
    description: str
    category: str
    servings: int
    minutes: int
    amounts: tuple[tuple[str, str], ...]
    steps: tuple[str, ...]

    @property
    def total_calories(self) -> Decimal:
        return sum((Decimal(amount) * Decimal(FOODS[key][2]) / 100 for key, amount in self.amounts), Decimal(0))

    def payload(self) -> RecipeInput:
        kcal = int((self.total_calories / self.servings).quantize(Decimal("1"), rounding=ROUND_HALF_UP))
        return RecipeInput(name=self.name, description=self.description,
            category=self.category, preparation_minutes=self.minutes,
            servings=self.servings, calories=kcal,
            ingredients=[{"name": FOODS[key][0], "quantity": Decimal(amount), "unit": FOODS[key][1]} for key, amount in self.amounts],
            preparation_steps=list(self.steps))


